import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { priceOrders, productCost, summarize } from "../src/lib/metrics.ts";
import type { Product, Warehouse } from "../src/lib/types.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const catalog = JSON.parse(readFileSync(path.join(root, "data/catalog.json"), "utf8")) as Product[];
const warehouse = JSON.parse(readFileSync(path.join(root, "data/warehouse.json"), "utf8")) as Warehouse;
const priced = priceOrders(catalog, warehouse.orders);
const summary = summarize(warehouse.customers, priced);

function sqlString(value: string): string {
  return `'${value.replaceAll("'", "''")}'`;
}

function timestamp(value: string): string {
  return `TIMESTAMP ${sqlString(value.replace("T", " ").replace("Z", " UTC"))}`;
}

function money(value: number): string {
  return value.toFixed(2);
}

const productRows = catalog
  .map(
    (product) => `  (${[
      sqlString(product.id),
      sqlString(product.name),
      sqlString(product.category),
      money(product.price),
      money(productCost(product.price)),
    ].join(", ")})`,
  )
  .join(",\n");

const customerRows = warehouse.customers
  .map(
    (customer) => `  (${[
      sqlString(customer.id),
      sqlString(customer.email),
      sqlString(customer.fullName),
      sqlString(customer.city),
      sqlString(customer.region),
      sqlString(customer.segment),
      timestamp(customer.createdAt),
    ].join(", ")})`,
  )
  .join(",\n");

const orderRows = priced
  .map(
    (order) => `  (${[
      sqlString(order.id),
      sqlString(order.customerId),
      timestamp(order.orderedAt),
      sqlString(order.status),
      sqlString(order.channel),
      money(order.subtotal),
      money(order.shipping),
      money(order.total),
    ].join(", ")})`,
  )
  .join(",\n");

const itemRows = priced
  .flatMap((order) => order.items)
  .map(
    (item) => `  (${[
      sqlString(item.id),
      sqlString(item.id.slice(0, item.id.lastIndexOf("-"))),
      sqlString(item.productId),
      String(item.quantity),
      money(item.unitPrice),
      money(item.lineTotal),
    ].join(", ")})`,
  )
  .join(",\n");

const bigQuerySeed = `-- Generated by scripts/emit-sql.ts from data/catalog.json and data/warehouse.json.
-- Fictional shoppers. Re-run the generator after editing the fixture.
-- Execute in the Cove project after terraform apply:
--   bq query --use_legacy_sql=false --project_id=PROJECT_ID < analytics/seed.sql

BEGIN
  DELETE FROM \`cove_analytics.order_items\` WHERE STARTS_WITH(order_id, 'o-');
  DELETE FROM \`cove_analytics.orders\` WHERE STARTS_WITH(order_id, 'o-');
  DELETE FROM \`cove_analytics.customers\` WHERE STARTS_WITH(customer_id, 'c-');
  DELETE FROM \`cove_analytics.products\` WHERE STARTS_WITH(product_id, 'harbor-')
    OR product_id IN (${catalog.map((product) => sqlString(product.id)).join(", ")});

  INSERT INTO \`cove_analytics.products\` (product_id, name, category, price, cost)
  VALUES
${productRows};

  INSERT INTO \`cove_analytics.customers\`
    (customer_id, email, full_name, city, region, segment, created_at)
  VALUES
${customerRows};

  INSERT INTO \`cove_analytics.orders\`
    (order_id, customer_id, ordered_at, status, channel, subtotal, shipping, total)
  VALUES
${orderRows};

  INSERT INTO \`cove_analytics.order_items\`
    (order_item_id, order_id, product_id, quantity, unit_price, line_total)
  VALUES
${itemRows};
END;
`;

function pgArray(values: string[]): string {
  return `ARRAY[${values.map(sqlString).join(", ")}]::text[]`;
}

const postgresRows = catalog
  .map(
    (product) => `  (${[
      sqlString(product.id),
      sqlString(product.slug),
      sqlString(product.name),
      sqlString(product.category),
      String(Math.round(product.price * 100)),
      sqlString(product.summary),
      sqlString(product.description),
      sqlString(product.materials),
      String(product.weightGrams),
      sqlString(product.origin),
      sqlString(product.sku),
      sqlString(product.image),
      pgArray(product.tags),
      sqlString(product.localInsight),
    ].join(", ")})`,
  )
  .join(",\n");

const postgresSeed = `-- Generated by scripts/emit-sql.ts. Replaces the demo catalog.
BEGIN;
TRUNCATE products;
INSERT INTO products (
  id, slug, name, category, price_cents, summary, description, materials,
  weight_grams, origin, sku, image, tags, local_insight
)
VALUES
${postgresRows};
COMMIT;
`;

const discoveryDir = path.join(root, "data/discovery");
mkdirSync(discoveryDir, { recursive: true });
const jsonl = catalog
  .map((product) =>
    JSON.stringify({
      id: product.id,
      jsonData: JSON.stringify({
        title: product.name,
        description: `${product.summary} ${product.description}`,
        categories: [product.category],
        price: product.price,
        brands: ["Cove Supply"],
        uri: `/products/${product.slug}`,
        materials: product.materials,
        tags: product.tags,
      }),
    }),
  )
  .join("\n");

writeFileSync(path.join(root, "analytics/seed.sql"), bigQuerySeed);
writeFileSync(path.join(root, "db/seed.sql"), postgresSeed);
writeFileSync(path.join(discoveryDir, "products.jsonl"), `${jsonl}\n`);

